export function useTranslations() {
  const [lang, setLang] = useState<Language>('id');
  const t = translations[lang];

  const toggleLanguage = () => {
    setLang((prev) => (prev === 'id' ? 'en' : 'id'));
  };

  return { lang, setLang, toggleLanguage, t };
}
