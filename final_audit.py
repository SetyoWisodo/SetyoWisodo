def check_docx():
    try:
        from docx import Document
    except ImportError:
        warn("docx", "python-docx tidak tersedia; dilewati")
        return
    for path, lang in (("book/publish/Surviving_the_Future_EN.docx", "EN"),
                       ("book/publish/Bertahan_Hidup_di_Masa_Depan_ID.docx", "ID")):
        if not os.path.exists(path):
            fail("docx", "%s tidak ada" % path)
            continue
        d = Document(path)
        txt = "\n".join(p.text for p in d.paragraphs)
        if len(d.tables) != 25:
            fail("docx", "%s: %d tabel (harus 25)" % (lang, len(d.tables)))
        if txt.count("compiled by the author") + txt.count("kompilasi penulis") < 24:
            fail("docx", "%s: baris sumber tabel tidak lengkap" % lang)
        if "ChatGPT" in txt:
            fail("docx", "%s: jejak AI" % lang)
        ok("docx", "%s: %d paragraf, 25 tabel, 24 baris sumber, tanpa jejak AI"
           % (lang, len(d.paragraphs)))


