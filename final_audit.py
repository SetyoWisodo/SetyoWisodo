def run_script(cmd, group, must_contain, timeout=900):
    """Jalankan skrip audit dan tuntut penanda sukses pada keluarannya."""
    import subprocess
    try:
        r = subprocess.run([sys.executable] + cmd, capture_output=True, text=True,
                           timeout=timeout)
    except Exception as exc:                       # noqa: BLE001
        fail(group, "%s gagal dijalankan: %s" % (" ".join(cmd), exc))
        return
    out = (r.stdout or "") + (r.stderr or "")
    if any(m in out for m in must_contain) and r.returncode == 0:
        tail = [l for l in out.strip().split("\n") if l.strip()][-1]
        ok(group, "%s → %s" % (" ".join(cmd), tail[:110]))
    else:
        tail = [l for l in out.strip().split("\n") if l.strip()][-3:]
        fail(group, "%s → %s" % (" ".join(cmd), " / ".join(tail)[:220]))


