def check_numbers(e, i):
    """Angka kunci yang pernah keliru harus tetap benar di semua tempat."""
    must = [
        (e, r"70 to 90 per cent of warm-water reefs", "karang 70–90 % pada 1,5 °C"),
        (e, r"more than 99 per cent \(IPCC, 2018\)", "karang >99 % pada 2 °C"),
        (e, r"1–25", "subsiden Jakarta 1–25 cm/tahun"),
        (i, r"1–25", "subsiden Jakarta 1–25 cm/tahun (ID)"),
        (e, r"US\$80–130 billion", "Uri US$80–130 miliar"),
        (i, r"US\$80–130 miliar", "Uri US$80–130 miliar (ID)"),
        (e, r"more than 200 \(Texas Department of State Health Services, 2023\)", "kematian Uri >200"),
        (e, r"at least a dozen", "Seoul selusin"),
        (e, r"more than 1,400 people in Louisiana alone", "Katrina Louisiana >1.400"),
        (e, r"NOAA National Centers for Environmental Information, 2024\)", "kerusakan Irma/Maria → NOAA"),
    ]
    bad = [label for text, pat, label in must if not re.search(pat, text)]
    if bad:
        fail("akurasi", "angka kunci tidak ditemukan: %s" % bad)
    else:
        ok("akurasi", "10 angka yang pernah keliru terverifikasi benar")

    # angka yang sudah dicabut tidak boleh hidup lagi
    dead = [(r"(?<![\d.])141(?![\d])", "Seoul 141 di tabel/gambar"),
            (r"US\$195 (billion|miliar)", "Uri US$195 miliar"),
            (r"costliest disaster in Texas", "klaim termahal Texas")]
    alive = []
    for pat, label in dead:
        for lang, text in (("EN", e), ("ID", i)):
            if re.search(pat, text):
                alive.append("%s:%s" % (lang, label))
    if alive:
        fail("akurasi", "angka yang sudah dicabut muncul lagi: %s" % alive)
    else:
        ok("akurasi", "angka yang sudah dicabut tidak muncul lagi di naskah")

    # konsistensi angka tabel vs gambar (teks alternatif)
    import figures
    md = e
    bad_fig = []
    for f in figures.FIGURES:
        num_id = f["id"]
        m = re.search(r"\[\[TABLE:Table %s " % re.escape(num_id), md)
        if not m:
            bad_fig.append("%s: tabel hilang" % num_id)
            continue
        j = md.find("\n\n", m.start())
        while md[j + 2:j + 3] == "|":
            j = md.find("\n\n", j + 2)
        table = md[m.start():j]
        for token in re.findall(r"[~]?[\d][\d.,]*", f["alt_en"]):
            plain = token.replace("~", "").rstrip(".,")
            if plain and plain not in table.replace(" ", ""):
                # toleransi: angka di teks alternatif boleh dibulatkan
                if not any(plain in cell for row in table.split("\n") for cell in row.split("|")):
                    bad_fig.append("%s: %s tidak ada di tabel" % (num_id, plain))
    if bad_fig:
        warn("gambar", "teks alternatif menyebut angka di luar tabel: %s" % bad_fig[:4])
    else:
        ok("gambar", "11 gambar: angka pada teks alternatif cocok dengan tabelnya")


