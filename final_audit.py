def write_report(path="FINAL_AUDIT.md"):
    groups = collections.OrderedDict()
    for status, group, msg in RESULTS:
        groups.setdefault(group, []).append((status, msg))
    fails = sum(1 for s, _, _ in RESULTS if s == "FAIL")
    warns = sum(1 for s, _, _ in RESULTS if s == "WARN")
    lines = ["# Audit Final Sebelum Terbit", "",
             "Dihasilkan oleh `final_audit.py`. Dijalankan ulang sampai nol FAIL.", "",
             "| Status | Jumlah |", "|---|---|",
             "| FAIL | **%d** |" % fails,
             "| WARN | %d |" % warns,
             "| OK | %d |" % sum(1 for s, _, _ in RESULTS if s == "OK"), ""]
    for group, items in groups.items():
        lines.append("## %s" % group)
        lines.append("")
        for status, msg in items:
            tag = {"OK": "✅", "WARN": "⚠️", "FAIL": "❌"}[status]
            lines.append("- %s %s" % (tag, msg))
        lines.append("")
    if fails:
        lines += ["## Temuan yang harus diperbaiki", ""]
        for group, msg in FAILS:
            lines.append("- **%s** — %s" % (group, msg))
        lines.append("")
    else:
        lines += ["## Putusan", "",
                  "**Nol temuan FAIL.** Naskah dan seluruh artefak produksi lolos "
                  "seluruh pemeriksaan otomatis dan siap dikunci untuk diunggah.", ""]
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(lines))
    return fails, warns


