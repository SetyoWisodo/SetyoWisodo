def check_epubs():
    import zipfile
    for path, lang in (("book/publish/Surviving_the_Future_EN.epub", "EN"),
                       ("book/publish/Bertahan_Hidup_di_Masa_Depan_ID.epub", "ID")):
        if not os.path.exists(path):
            fail("epub", "%s tidak ada" % path)
            continue
        z = zipfile.ZipFile(path)
        names = z.namelist()
        if "mimetype" not in names:
            fail("epub", "%s: mimetype hilang" % lang)
        if not any(n.endswith(".ncx") for n in names):
            fail("epub", "%s: NCX hilang" % lang)
        if not any(n.endswith(".opf") for n in names):
            fail("epub", "%s: OPF hilang" % lang)
        html = "".join(z.read(n).decode("utf-8", "ignore")
                       for n in names if n.endswith(("xhtml", "html")))
        if html.count('class="tablesource"') < 24:
            fail("epub", "%s: baris sumber tabel %d/24" % (lang, html.count('class="tablesource"')))
        if "<img" in html and "alt=" not in html:
            fail("epub", "%s: gambar tanpa alt" % lang)
        if 'lang="' not in html[:4000]:
            warn("epub", "%s: atribut lang tidak terlihat di dokumen pertama" % lang)
        ok("epub", "%s: %d berkas, nav+NCX+OPF, 24 baris sumber tabel, alt teks ada"
           % (lang, len(names)))


