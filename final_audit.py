def check_pdfs():
    try:
        import pymupdf
    except ImportError:
        warn("pdf", "pymupdf tidak tersedia; pemeriksaan PDF dilewati")
        return
    for path, lang in ((EN_PDF, "EN"), (ID_PDF, "ID")):
        if not os.path.exists(path):
            fail("pdf", "%s tidak ada" % path)
            continue
        d = pymupdf.open(path)
        n = d.page_count
        meta = d.metadata or {}
        txt_all = "".join(d[i].get_text() for i in range(n))

        if not meta.get("title") or not meta.get("author"):
            fail("pdf", "%s: metadata judul/penulis kosong" % lang)
        if "ChatGPT" in txt_all or "large language model" in txt_all.lower():
            fail("pdf", "%s: jejak AI di PDF" % lang)
        blank = [i + 1 for i in range(n) if len(d[i].get_text().strip()) < 20]
        if blank:
            warn("pdf", "%s: halaman hampir kosong: %s" % (lang, blank[:5]))
        src_lines = txt_all.count("Source: compiled by the author") + txt_all.count("Sumber: kompilasi penulis")
        if src_lines < 24:
            fail("pdf", "%s: hanya %d baris sumber tabel tercetak" % (lang, src_lines))

        # nomor halaman tercetak di setiap halaman isi
        no_folio = []
        for i in range(15, n - 1):
            t = d[i].get_text().strip().split("\n")
            if not t:
                continue
            tail = " ".join(t[-2:])
            if not re.search(r"\b\d{1,3}\b", tail):
                no_folio.append(i + 1)
        if no_folio:
            warn("pdf", "%s: %d halaman tanpa folio terbaca (mis. %s)" % (lang, len(no_folio), no_folio[:4]))

        # tanda kutip dan satuan di teks yang dicetak
        body_txt = "".join(d[i].get_text() for i in range(15, n - 4))
        if body_txt.count("'") > 2 or body_txt.count('"') > 0:
            fail("pdf", "%s: %d apostrof/tanda kutip lurus tercetak"
                 % (lang, body_txt.count("'") + body_txt.count('"')))
        no_space = len(re.findall(r"\d°C", body_txt))
        if no_space:
            fail("pdf", "%s: %d penulisan °C tanpa spasi" % (lang, no_space))
        # indeks harus memuat nomor halaman
        idx_page = None
        for i in range(n - 1, 0, -1):
            head = d[i].get_text().strip().split("\n")[0]
            if head in ("INDEX", "INDEKS"):
                idx_page = i
                break
        if idx_page is None:
            fail("pdf", "%s: halaman indeks tidak ditemukan" % lang)
        else:
            idx_txt = "".join(d[k].get_text() for k in range(idx_page, min(n, idx_page + 6)))
            hits = len(re.findall(r"\b\d{1,3}\b", idx_txt))
            if hits < 100:
                fail("pdf", "%s: indeks hanya memuat %d angka halaman" % (lang, hits))
            else:
                ok("pdf", "%s: indeks memuat %d nomor halaman" % (lang, hits))

        # daftar isi menunjuk halaman yang benar untuk beberapa bab
        toc = d.get_toc()
        bad_toc = 0
        for lvl, title, page in toc[:40]:
            if page < 1 or page > n:
                bad_toc += 1
        if bad_toc:
            fail("pdf", "%s: %d entri outline menunjuk halaman di luar rentang" % (lang, bad_toc))

        ok("pdf", "%s: %d halaman, metadata lengkap, %d baris sumber tabel, outline %d entri"
           % (lang, n, src_lines, len(toc)))
    return


