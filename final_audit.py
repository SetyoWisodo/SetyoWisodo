def check_placeholders(e, i):
    bad = []
    for lang, text in (("EN", e), ("ID", i)):
        for word in ("TODO", "TBD", "XXX", "lorem ipsum", "PLACEHOLDER",
                     "[isi", "\ufffd"):
            if word in text:
                bad.append("%s:%s" % (lang, word))
    if bad:
        fail("kebersihan", "teks sisa/placeholder: %s" % bad)
    else:
        ok("kebersihan", "tidak ada placeholder atau karakter rusak")


def check_ref_structure(e, i):
    for lang, text, subs in (("EN", e, ("## Works Cited", "## Further Reading")),
                             ("ID", i, ("## Karya yang Dikutip", "## Bacaan Lanjutan"))):
        seg = section(text, subs[0], "# Index" if lang == "EN" else "# Indeks")
        if subs[1] not in seg:
            fail("pustaka", "%s: subbagian '%s' hilang" % (lang, subs[1]))
            continue
        a = [l[2:].strip() for l in seg.split("\n") if l.startswith("- ")]
        cited = [x for x in a if x][:len(a)]
        if not cited:
            fail("pustaka", "%s: daftar pustaka kosong" % lang)
        ok("pustaka", "%s: struktur dua subbagian utuh (%d entri)" % (lang, len(a)))

