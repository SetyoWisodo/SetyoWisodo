def check_parity(e, i):
    # jumlah tabel, gambar, bab, subbab
    for what, a, b in (
            ("tabel", len(re.findall(r"\[\[TABLE:", e)), len(re.findall(r"\[\[TABLE:", i))),
            ("gambar", len(re.findall(r"(?m)^!\[", e)), len(re.findall(r"(?m)^!\[", i))),
            ("bab", len(re.findall(r"(?m)^# Chapter ", e)), len(re.findall(r"(?m)^# Bab ", i)))):
        if a != b:
            fail("paritas", "%s EN %d != ID %d" % (what, a, b))
    if not FAILS or all(g != "paritas" for g, _ in FAILS):
        ok("paritas", "tabel, gambar, dan bab sama jumlahnya di kedua edisi")

    # kata badan: rasio wajar (ID biasanya lebih ringkas/padat)
    we = num(body_of(e))
    wi = num(body_of(i, "# Daftar Pustaka"))
    ratio = wi / we
    if not (0.7 < ratio < 0.95):
        warn("paritas", "rasio kata ID/EN %.2f di luar rentang biasa (0,70–0,95)" % ratio)
    else:
        ok("paritas", "kata badan EN %s / ID %s (rasio %.2f)" % (f"{we:,}", f"{wi:,}", ratio))

    # harga
    for path, pats in (("HARGA_EN.md", ["$45", "$29", "$59"]),
                       ("GUMROAD.md", ["$45", "$29", "$59"])):
        if os.path.exists(path):
            t = read(path)
            miss = [p for p in pats if p not in t]
            if miss:
                fail("harga", "%s tidak memuat %s" % (path, miss))
    if os.path.exists("GUMROAD.md") and all(p in read("GUMROAD.md") for p in ("$45", "$29", "$59")):
        ok("harga", "EN $45 · ID $29 · bundle $59 konsisten di dokumen penjualan")


