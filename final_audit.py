def check_style(e, i):
    """Gaya diperiksa pada sumber markdown untuk hal yang tak bisa dinormalkan
    renderer (kata terulang, elipsis, spasi ganda), dan pada PDF untuk tanda
    kutip serta satuan, karena PDF-lah yang dibaca pembeli."""
    for lang, text in (("EN", e), ("ID", i)):
        body = body_of(text) if lang == "EN" else body_of(text, "# Daftar Pustaka")
        prose = "\n".join(l for l in body.split("\n")
                          if not l.startswith(("#", "|", "[[", "!", "-")))
        dup = re.findall(r"\b(\w{3,})\s+\1\b", prose, re.I)
        dup = [d for d in dup if d.lower() not in ("that", "had", "yang", "dan")]
        if dup:
            fail("gaya", "%s: kata terulang: %s" % (lang, collections.Counter(dup).most_common(4)))
        n_space = len(re.findall(r"[a-z]  +[a-z]", prose))
        if n_space:
            fail("gaya", "%s: %d spasi ganda di dalam kalimat" % (lang, n_space))
        if "..." in prose:
            fail("gaya", "%s: elipsis tiga titik (harus …)" % lang)
    if not [1 for g, _ in FAILS if g == "gaya"]:
        ok("gaya", "tanpa kata terulang, tanpa spasi ganda, elipsis tipografis")


