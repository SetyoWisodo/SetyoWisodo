EN_PDF = "Surviving_the_Future.pdf"
ID_PDF = "Surviving_the_Future_ID.pdf"
RESULTS = []      # (status, kelompok, pesan)
FAILS = []


def rec(status, group, msg):
    RESULTS.append((status, group, msg))
    if status == "FAIL":
        FAILS.append((group, msg))


def ok(group, msg):
    rec("OK", group, msg)


def fail(group, msg):
    rec("FAIL", group, msg)


def warn(group, msg):
    rec("WARN", group, msg)


# ----------------------------------------------------------------- utilitas --
def read(path):
    with open(path, encoding="utf-8") as fh:
        return fh.read()


def blocks(text):
    return text.split("\n\n")


def chapters(text):
    """[(judul, isi)] untuk setiap heading level 1."""
    parts = re.split(r"(?m)^# ", text)
    out = []
    for p in parts[1:]:
        title, _, body = p.partition("\n")
        out.append((title.strip(), body))
    return out


def body_of(text, marker="# References"):
    return text[:text.find(marker)] if marker in text else text


def section(text, start, end):
    i = text.find(start)
    if i < 0:
        return ""
    j = text.find(end, i + len(start)) if end else -1
    return text[i:] if j < 0 else text[i:j]


def list_items(seg):
    return [l[2:].strip() for l in seg.split("\n") if l.startswith("- ")]


def num(lang_text):
    return len(lang_text.split())


# -------------------------------------------------------------------- 1. teks --
def check_manuscript():
    e, i = read(EN), read(ID)
    eb, ib = body_of(e), body_of(i, "# Daftar Pustaka")

    n_e = len(re.findall(r"(?m)^# Chapter \d+:", e))
    n_i = len(re.findall(r"(?m)^# Bab \d+:", i))
    if n_e != 24:
        fail("struktur", "EN: %d bab (harus 24)" % n_e)
    if n_i != 24:
        fail("struktur", "ID: %d bab (harus 24)" % n_i)

    # setiap bab: Case Study + Future Scenarios bernomor, minimal 10 subbab
    for lang, text, pat_case, pat_future in (
            ("EN", e, r"^## \d+\.\d+ Case Study", r"^## \d+\.\d+ Future Scenarios"),
            ("ID", i, r"^## \d+\.\d+ Studi Kasus", r"^## \d+\.\d+ Skenario")):
        bad = []
        for title, body in chapters(text):
            if not title.startswith("Chapter") and not title.startswith("Bab"):
                continue
            n_sub = len(re.findall(r"(?m)^## \d+\.\d+ ", body))
            if n_sub < 10:
                bad.append("%s subbab=%d" % (title[:28], n_sub))
            if not re.search(pat_case, body, re.M):
                bad.append("%s tanpa Case Study" % title[:28])
            if not re.search(pat_future, body, re.M):
                bad.append("%s tanpa Future Scenarios" % title[:28])
        if bad:
            fail("struktur", "%s: %s" % (lang, "; ".join(bad[:4])))
        else:
            ok("struktur", "%s: 24 bab, subbab bernomor, Case Study + Future Scenarios ada" % lang)

    # label lampiran yang dilarang
    for lang, text in (("EN", e), ("ID", i)):
        if re.search(r"(?m)^#+ .*(Appendix [A-D]|Lampiran [A-D])\b", text):
            fail("struktur", "%s masih memakai label Appendix/Lampiran" % lang)
    ok("struktur", "tidak ada label Appendix A–D / Lampiran A–D")

    # jejak AI
    # yang dilarang adalah mengungkap peran AI dalam PRODUKSI buku, bukan
    # membahas AI sebagai topik (mis. deepfake di bab lingkungan informasi).
    PROV = ("written by ai", "generated by ai", "ai-assisted", "ai-generated by",
            "produced with ai", "drafted with ai", "with the help of ai",
            "dibuat dengan ai", "dibantu ai", "disusun dengan ai",
            "chatgpt", "gpt-4", "claude", "gemini", "large language model",
            "model bahasa besar", "asisten ai")
    prov = []
    for lang, text in (("EN", e), ("ID", i)):
        low = text.lower()
        for word in PROV:
            if word in low:
                prov.append("%s:%s" % (lang, word))
    # halaman hak cipta dan tentang penulis tidak boleh menyebut AI sama sekali
    frontback = (section(e, "# Preface", "# Chapter 1") + section(e, "# About the Author", "") +
                 section(i, "# Prakata", "# Bab 1") + section(i, "# Tentang Penulis", ""))
    if "AI" in frontback or "kecerdasan buatan" in frontback.lower():
        prov.append("front/back matter menyebut AI")
    if prov:
        fail("kebersihan", "jejak peran AI dalam produksi: %s" % prov)
    else:
        ok("kebersihan", "nol jejak peran AI dalam produksi (topik AI di badan dibolehkan)")

    # frasa yang dilarang
    for phrase in ("From an academic perspective", "Dari perspektif akademis"):
        if phrase in e or phrase in i:
            fail("kebersihan", "frasa terlarang muncul: %s" % phrase)

    # epilog blok penutup bab yang dihapus permanen
    for pat, label in ((r"(?m)^## In sum\b", "In sum"),
                       (r"(?m)^## Key takeaways\b", "Key takeaways"),
                       (r"(?m)^## Sources cited\b", "Sources cited"),
                       (r"(?m)^## For reflection\b", "For reflection"),
                       (r"(?m)^## Ringkasan Bab\b", "Ringkasan Bab")):
        if re.search(pat, e) or re.search(pat, i):
            fail("struktur", "blok penutup bab muncul kembali: %s" % label)
    ok("struktur", "tidak ada blok penutup bab (In sum / Key takeaways / Sources cited / For reflection)")

    return e, i, eb, ib


# ---------------------------------------------------------------- 2. aparatus --
def check_apparatus(e, i):
    # tabel & sumber
    te = re.findall(r"\[\[TABLE:(.*?)\]\]", e)
    ti = re.findall(r"\[\[TABLE:(.*?)\]\]", i)
    if len(te) != 25 or len(ti) != 25:
        fail("tabel", "jumlah tabel EN %d / ID %d (harus 25)" % (len(te), len(ti)))
    else:
        ok("tabel", "25 tabel di kedua edisi")
    src_e = [t for t in te if "||" in t]
    src_i = [t for t in ti if "||" in t]
    # Table P.1 memakai kolom Source di dalam tabel, bukan baris sumber
    p1_e = re.search(r"\| Indicator \| Value \| Source \|", e) is not None
    p1_i = re.search(r"\| Indikator \| Nilai \| Sumber \|", i) is not None
    n_src_e = len(src_e) + (1 if p1_e else 0)
    n_src_i = len(src_i) + (1 if p1_i else 0)
    if n_src_e < 25 or n_src_i < 25:
        fail("tabel", "tabel bersumber: EN %d/25, ID %d/25" % (n_src_e, n_src_i))
    else:
        ok("tabel", "25/25 tabel bersumber (24 baris + kolom Source Table P.1), EN+ID")
    # sumber harus menyebut tahun dan nama
    for lang, lst in (("EN", src_e), ("ID", src_i)):
        bad = [t.split("||")[0][:40] for t in lst
               if not re.search(r"\b(18|19|20)\d{2}\b", t.split("||")[1])]
        if bad:
            fail("tabel", "%s: baris sumber tanpa tahun: %s" % (lang, bad[:3]))

    # tabel & gambar dirujuk dari prosa
    for lang, text, lab, fig in (("EN", e, "Table", "Figure"), ("ID", i, "Tabel", "Gambar")):
        stripped = re.sub(r"(?m)^\[\[TABLE:[^\]]*\]\]$", "", text)
        stripped = re.sub(r"(?m)^!\[[^\]]*\]\([^)]*\)\|\|[^\n]*$", "", stripped)
        miss = []
        for m in re.finditer(r"\[\[TABLE:%s (\d+\.\d+)" % lab, text):
            n = m.group(1)
            if not re.search(r"\b%s %s\b" % (lab, re.escape(n)), stripped):
                miss.append(n)
        if miss:
            fail("rujukan", "%s: tabel tak dirujuk di prosa: %s" % (lang, miss))
        figs = re.findall(r"!\[%s (\d+\.\d+)" % fig, text)
        fmiss = [n for n in figs
                 if not re.search(r"\b%s %s\b" % (fig, re.escape(n)), stripped)]
        if fmiss:
            fail("rujukan", "%s: gambar tak dirujuk di prosa: %s" % (lang, fmiss))
        if not miss and not fmiss:
            ok("rujukan", "%s: semua tabel dan gambar dirujuk dari prosa" % lang)

    # glosarium
    g_e = list_items(section(e, "# Glossary", "# Analytical Caveats"))
    g_i = list_items(section(i, "# Glosarium", "# Catatan Sumber Peristiwa"))
    if len(g_e) < 55 or len(g_i) < 55:
        fail("aparatus", "glosarium EN %d / ID %d (minimal 55)" % (len(g_e), len(g_i)))
    else:
        ok("aparatus", "glosarium EN %d / ID %d istilah" % (len(g_e), len(g_i)))
    for lang, lst in (("EN", g_e), ("ID", g_i)):
        if lst != sorted(lst, key=lambda x: x.lower()):
            fail("aparatus", "%s: glosarium tidak A–Z" % lang)
        no_def = [x[:25] for x in lst if ":" not in x]
        if no_def:
            fail("aparatus", "%s: entri glosarium tanpa definisi: %s" % (lang, no_def[:3]))
    if all(len(x.split()) >= 4 for x in g_e):
        ok("aparatus", "setiap entri glosarium punya definisi substantif")

    # catatan sumber peristiwa
    n_e = list_items(section(e, "# Notes on Event Sources", "# References"))
    n_i = list_items(section(i, "# Catatan Sumber Peristiwa", "# Daftar Pustaka"))
    if len(n_e) < 28 or len(n_i) < 28:
        fail("aparatus", "catatan peristiwa EN %d / ID %d (minimal 28)" % (len(n_e), len(n_i)))
    else:
        ok("aparatus", "catatan peristiwa EN %d / ID %d" % (len(n_e), len(n_i)))

    # pustaka: jumlah, A–Z, setiap entri punya tahun + judul italik/kutip
    # dua subbagian, masing-masing harus A–Z
    def subsections(text, start, end, heads):
        seg = section(text, start, end)
        out = {}
        for k, h in enumerate(heads):
            i0 = seg.find(h)
            i1 = seg.find(heads[k + 1], i0 + 1) if k + 1 < len(heads) else len(seg)
            out[h] = list_items(seg[i0:i1]) if i0 >= 0 else []
        return out

    ref_e = subsections(e, "# References", "# Index",
                        ["## Works Cited", "## Further Reading"])
    ref_i = subsections(i, "# Daftar Pustaka", "# Indeks",
                        ["## Karya yang Dikutip", "## Bacaan Lanjutan"])
    r_e = [x for v in ref_e.values() for x in v]
    r_i = [x for v in ref_i.values() for x in v]
    if len(r_e) != len(r_i):
        fail("pustaka", "jumlah entri EN %d != ID %d" % (len(r_e), len(r_i)))
    for lang, refs in (("EN", ref_e), ("ID", ref_i)):
        for head, items in refs.items():
            if not items:
                fail("pustaka", "%s: subbagian %s kosong" % (lang, head))
            elif items != sorted(items, key=lambda x: x.lower()):
                bad = [b[:45] for a, b in zip(items, sorted(items, key=str.lower)) if a != b][:2]
                fail("pustaka", "%s %s tidak A–Z, mis. %s" % (lang, head, bad))
    no_year = [x[:40] for x in r_e if not re.search(r"\b(18|19|20)\d{2}[a-z]?\b", x)]
    if no_year:
        fail("pustaka", "entri tanpa tahun: %s" % no_year[:3])
    if len(r_e) == len(r_i) and not no_year:
        ok("pustaka", "%d entri di kedua edisi, A–Z, semua bertahun" % len(r_e))

    # indeks berhalaman diperiksa pada PDF (lihat check_pdfs)
    i_e = list_items(section(e, "# Index", "# About the Author"))
    ok("aparatus", "indeks EN %d entri (nomor halaman diverifikasi di PDF)" % len(i_e))


